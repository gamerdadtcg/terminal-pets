#!/usr/bin/env node
/**
 * Export top 150 arcade wallets into web/lib/arcade-gtd-wallets.ts
 *
 * Usage (from web/):
 *   node scripts/export-arcade-gtd.mjs
 *   ARCADE_SCORES_JSON=./data/arcade-scores.json node scripts/export-arcade-gtd.mjs
 *   ARCADE_BOARD_URL=https://terminalpets.xyz/api/arcade/board \
 *     ARCADE_EXPORT_SECRET=... node scripts/export-arcade-gtd.mjs
 *
 * Then merge + redeploy before Fri Sep 18 7:00 AM PT.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CAP = 150;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "lib", "arcade-gtd-wallets.ts");

async function loadRows() {
  const url = process.env.ARCADE_BOARD_URL?.trim();
  const secret = (
    process.env.ARCADE_EXPORT_SECRET ||
    process.env.ARCADE_HMAC_SECRET ||
    ""
  ).trim();
  if (url) {
    const response = await fetch(`${url.replace(/\/$/, "")}?export=1`, {
      headers: secret ? { "x-arcade-export": secret } : {},
    });
    if (!response.ok) {
      throw new Error(`Board fetch failed: ${response.status}`);
    }
    const body = await response.json();
    return body.board ?? [];
  }

  const file =
    process.env.ARCADE_SCORES_JSON?.trim() ||
    path.join(root, "data", "arcade-scores.json");
  const raw = fs.readFileSync(file, "utf8");
  const parsed = JSON.parse(raw);
  const rows = (parsed.rows ?? []).slice();
  rows.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    return a.submittedAt - b.submittedAt;
  });
  return rows.map((row, index) => ({
    rank: index + 1,
    wallet: row.wallet,
    score: row.score,
  }));
}

async function main() {
  const rows = await loadRows();
  const winners = rows.slice(0, CAP);
  const addresses = winners.map((row) => String(row.wallet).toLowerCase());
  const unique = [...new Set(addresses)];
  const body = `import { getAddress, type Address } from "viem";

/**
 * Top 150 arcade wallets, merged into hub GTD after contest close.
 *
 * Generated by \`node scripts/export-arcade-gtd.mjs\` (from web/). Do not hand-edit
 * the address list unless you are locking the export for the Friday redeploy.
 */
export const ARCADE_GTD_REASON = "Arcade top 150";

/** Seed / export list — mixed-case 0x addresses are fine. */
export const ARCADE_GTD_WALLET_ADDRESSES = [
${unique.map((wallet) => `  "${wallet}",`).join("\n")}
] as const;

function checksum(address: string): Address {
  return getAddress(address.toLowerCase());
}

export const ARCADE_GTD_WALLETS: readonly Address[] =
  ARCADE_GTD_WALLET_ADDRESSES.map(checksum);

export const ARCADE_GTD_WALLET_SET: ReadonlySet<string> = new Set(
  ARCADE_GTD_WALLETS.map((address) => address.toLowerCase()),
);

export function isExportedArcadeGtdWallet(address: string): boolean {
  try {
    return ARCADE_GTD_WALLET_SET.has(checksum(address.trim()).toLowerCase());
  } catch {
    return false;
  }
}
`;
  fs.writeFileSync(outFile, body);
  console.log(`Wrote ${unique.length} wallets to ${path.relative(root, outFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
